from __future__ import annotations

from typing import Any

from shepherd_contracts import (
    CaseSpec,
    EnvironmentDataRefs,
    FarmBoundarySpec,
    LocalCoordinateSystem,
)

from .case.models import EnvironmentCase, TerrainGeneration
from .case.models import TerrainProvenance
from .case.validator import validate_environment_case
from .case.writer import validate_case_id
from .farm.boundary import FarmBoundary
from .terrain.generators import TerrainKind, generate_terrain
from .terrain.heightmap import TerrainGridSpec
from .terrain.quality import calculate_terrain_quality
from .sources.models import TerrainSourceResult


def create_synthetic_case(
    *,
    case_id: str,
    terrain_kind: TerrainKind | str,
    grid: TerrainGridSpec,
    farm_boundary: FarmBoundary,
    generation_parameters: dict[str, Any] | None = None,
    seed: int = 0,
    schema_version: str = "1.0",
    origin_description: str = "south-west corner of the synthetic terrain extent",
    vertical_datum: str = "synthetic local elevation datum",
) -> EnvironmentCase:
    validate_case_id(case_id)
    terrain_type = TerrainKind(terrain_kind)
    if farm_boundary.coordinate_system_name != f"{case_id}-local-enu":
        raise ValueError("farm boundary coordinate system must match the generated Case")
    parameters = dict(generation_parameters or {})
    heightmap = generate_terrain(
        terrain_type,
        grid,
        parameters=parameters,
        seed=seed,
    )
    case_spec = CaseSpec(
        schema_version=schema_version,
        case_id=case_id,
        coordinate_system=LocalCoordinateSystem(
            name=f"{case_id}-local-enu",
            origin_description=origin_description,
            vertical_datum=vertical_datum,
        ),
        environment=EnvironmentDataRefs(terrain="terrain.tif"),
        farm_boundary=FarmBoundarySpec(
            data_ref="farm_boundary.geojson",
            bounds=farm_boundary.bounds,
        ),
    )
    environment_case = EnvironmentCase(
        case_spec=case_spec,
        heightmap=heightmap,
        farm_boundary=farm_boundary,
        generation=TerrainGeneration(
            method=terrain_type.value,
            parameters=parameters,
            seed=seed,
        ),
        provenance=TerrainProvenance(
            source="synthetic",
            dataset=terrain_type.value,
            elevation_type="synthetic surface",
            source_crs=None,
            vertical_datum=vertical_datum,
            effective_resolution_m=grid.cell_size_m,
            output_cell_size_m=grid.cell_size_m,
            fill_method="none",
            attribution="Generated by field-environment",
        ),
        quality=calculate_terrain_quality(heightmap.values, heightmap.grid),
    )
    validate_environment_case(environment_case)
    return environment_case


def create_case_from_terrain_source(
    *,
    case_id: str,
    source_result: TerrainSourceResult,
    farm_boundary: FarmBoundary,
    schema_version: str = "1.0",
) -> EnvironmentCase:
    validate_case_id(case_id)
    if farm_boundary.coordinate_system_name != source_result.coordinate_system.name:
        raise ValueError("farm boundary coordinate system must match terrain source")
    case_spec = CaseSpec(
        schema_version=schema_version,
        case_id=case_id,
        coordinate_system=source_result.coordinate_system,
        environment=EnvironmentDataRefs(
            terrain="terrain.tif",
            source_directory="source" if source_result.source_artifacts else None,
        ),
        farm_boundary=FarmBoundarySpec(
            data_ref="farm_boundary.geojson",
            bounds=farm_boundary.bounds,
        ),
    )
    environment_case = EnvironmentCase(
        case_spec=case_spec,
        heightmap=source_result.heightmap,
        farm_boundary=farm_boundary,
        generation=source_result.generation,
        provenance=source_result.provenance,
        quality=source_result.quality,
        source_artifacts=source_result.source_artifacts,
    )
    validate_environment_case(environment_case)
    return environment_case
